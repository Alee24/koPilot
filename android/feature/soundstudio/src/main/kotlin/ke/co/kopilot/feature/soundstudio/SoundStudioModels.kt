package ke.co.kopilot.feature.soundstudio

import kotlinx.serialization.Serializable

enum class EngineCategory(val displayName: String, val cylinderCount: Int, val isDiesel: Boolean) {
    FOUR_CYL_PETROL("4-Cylinder Petrol", 4, false),
    INLINE_SIX_SPORTS("Inline-6 Sports", 6, false),
    V6_PERFORMANCE("V6 Performance", 6, false),
    V8_MUSCLE("V8 Muscle", 8, false),
    V10_SUPERCAR("V10 Supercar", 10, false),
    V12_SUPERCAR("V12 Supercar", 12, false),
    TURBO_PERFORMANCE("Turbocharged Performance", 4, false),
    DIESEL_PICKUP("Diesel Pickup", 4, true),
    HEAVY_DIESEL_TRUCK("Heavy-Duty Diesel Truck", 6, true),
    CLASSIC_ENGINE("Classic Carbureted", 8, false),
    CUSTOM_IMPORTED("Custom Imported Pack", 4, false),
}

enum class EngineSimulationMode(val label: String, val description: String) {
    AUTHENTIC_RPM(
        "Authentic RPM",
        "Follows actual OBD-II engine RPM and throttle position directly.",
    ),
    SPORT_SIMULATION(
        "Sport Simulation",
        "Enhanced performance character with richer harmonics and overrun response (simulation only).",
    ),
}

enum class RpmSampleSlot(val label: String, val defaultMinRpm: Int, val defaultMaxRpm: Int, val baseRpm: Int) {
    IDLE("Idle", 600, 1200, 800),
    LOW("Low RPM", 1000, 2600, 1800),
    MEDIUM("Medium RPM", 2200, 4500, 3200),
    HIGH("High RPM", 4000, 7500, 5600),
    ACCEL("Acceleration Load", 1500, 6500, 3500),
    DECEL("Deceleration Overrun", 1400, 5500, 3000),
}

@Serializable
data class EngineSampleLayer(
    val slot: RpmSampleSlot,
    val fileName: String,
    val minRpm: Int,
    val maxRpm: Int,
    val baseRpm: Int,
    val sampleRateHz: Int,
    val durationSec: Float,
)

@Serializable
data class EngineSoundProfile(
    val id: String,
    val name: String,
    val category: EngineCategory,
    val description: String,
    val configuration: String,
    val characteristics: String,
    val idleRpm: Int = 750,
    val redlineRpm: Int = 6800,
    val fundamentalScale: Float = 1.0f,
    val exhaustWarmth: Float = 0.55f,
    val intakeGrowl: Float = 0.40f,
    val turboSpoolAmount: Float = 0.0f,
    val isCustomImported: Boolean = false,
    val sampleLayers: List<EngineSampleLayer> = emptyList(),
)

@Serializable
data class EngineAudioSettings(
    val masterVolume: Float = 0.75f,
    val soundIntensity: Float = 0.80f,
    val rpmResponsiveness: Float = 0.75f,     // 0.2 (smooth) .. 1.0 (snappy)
    val crossfadeSmoothing: Float = 0.65f,
    val simulationMode: EngineSimulationMode = EngineSimulationMode.AUTHENTIC_RPM,
    val muteOnPhoneCall: Boolean = true,
    val pauseOnObdDisconnect: Boolean = true,
    val pauseOnSafetyAlert: Boolean = true,
    val batterySavingMode: Boolean = false,
    val turboEffectsEnabled: Boolean = true,
)

data class SoundStudioUiState(
    val isRunning: Boolean = false,
    val isPreviewActive: Boolean = false,
    val previewRpm: Int = 800,
    val isMuted: Boolean = false,
    val isDuckedOrPausedReason: String? = null,
    val obdConnected: Boolean = false,
    val obdStatusLabel: String = "OBD-II Disconnected",
    val liveRpm: Float = 0f,
    val liveThrottlePct: Float? = null,
    val liveSpeedKmh: Int? = null,
    val liveLoadPct: Float? = null,
    val isObdStale: Boolean = false,
    val audioOutputRoute: String = "Phone Speaker",
    val audioLatencyEstimateMs: Int = 25,
    val selectedProfile: EngineSoundProfile = BuiltInEngineProfiles.ALL.first(),
    val profiles: List<EngineSoundProfile> = BuiltInEngineProfiles.ALL,
    val audioSettings: EngineAudioSettings = EngineAudioSettings(),
    val waveformSnapshot: List<Float> = List(32) { 0f },
)

